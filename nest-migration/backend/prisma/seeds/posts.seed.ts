export async function seedPosts(prisma: PrismaClient) {
  console.log('  → Populando Posts e Recomendações...');

  for (const post of POSTS_SEED) {
    await prisma.post.upsert({
      where: { id: post.id },
      update: {},
      create: post,
    });
  }

  for (const rec of RECOMMENDATIONS_SEED) {
    await prisma.postRecommendation.upsert({
      where: {
        postId_recommendedPostId: {
          postId: rec.postId,
          recommendedPostId: rec.recommendedPostId,
        },
      },
      update: {},
      create: rec,
    });
  }
}
